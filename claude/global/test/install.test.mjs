import test from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const INSTALLER = path.resolve(HERE, "..", "install.mjs");
// The block older kit versions wrote into ~/.claude/CLAUDE.md; installs now only remove it.
const BODY = "@~/.claude/orchestration/claude/CLAUDE.orchestration.md";
const NEW_BLOCK = `<!-- BEGIN orchestration-kit:claude-md -->\n${BODY}\n<!-- END orchestration-kit:claude-md -->`;
const LEGACY_BLOCK = "<!-- BEGIN frontier-orchestration (managed by frontier_model_orchestration/claude/global/install.mjs) -->\nlegacy contents\n<!-- END frontier-orchestration -->";
const GENERATED = "<!-- Generated by orchestration-kit";

const sha256 = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");

function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "installer-test-"));
  const home = path.join(dir, "home");
  fs.mkdirSync(home, { recursive: true });
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const env = { ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, ".codex"), APPDATA: home };
  const claude = path.join(home, ".claude");
  const claudeMd = path.join(claude, "CLAUDE.md");
  const settings = path.join(claude, "settings.json");
  const rulesFile = path.join(claude, "rules", "orchestration-kit.md");
  const deployed = path.join(claude, "orchestration", "deployed.json");
  const run = (...args) => spawnSync(process.execPath, [INSTALLER, ...args], { encoding: "utf8", env, timeout: 30000, maxBuffer: 4 * 1024 * 1024 });
  const backups = () => {
    if (!fs.existsSync(claude)) return [];
    const found = [];
    const visit = (dirPath) => {
      for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
        const full = path.join(dirPath, entry.name);
        if (entry.isDirectory()) visit(full);
        else if (entry.name.includes(".bak-")) found.push(full);
      }
    };
    visit(claude);
    return found;
  };
  return { dir, home, claude, claudeMd, settings, rulesFile, deployed, env, run, backups };
}

/** Create ~/.claude/CLAUDE.md with the given text. Input: fixture, text. Output: none. */
function writeClaudeMd(f, text) {
  fs.mkdirSync(f.claude, { recursive: true });
  fs.writeFileSync(f.claudeMd, text);
}

test("fresh install writes the rules file and creates no CLAUDE.md", (t) => {
  const f = fixture(t);
  const result = f.run();
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.ok(fs.readFileSync(f.rulesFile, "utf8").startsWith(GENERATED));
  assert.equal(fs.existsSync(f.claudeMd), false);
  assert.equal(JSON.parse(fs.readFileSync(f.deployed, "utf8")).rules_file_sha256, sha256(f.rulesFile));
  assert.equal(fs.existsSync(path.join(f.claude, "orchestration", "claude", "CLAUDE.orchestration.md")), false);
  assert.ok(fs.existsSync(path.join(f.claude, "orchestration", "overrides")));
});

test("CLAUDE.md without a block is not touched", (t) => {
  const f = fixture(t);
  writeClaudeMd(f, "mine\n");
  const mtime = fs.statSync(f.claudeMd).mtimeMs;
  const result = f.run();
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), "mine\n");
  assert.equal(fs.statSync(f.claudeMd).mtimeMs, mtime);
  assert.equal(f.backups().length, 0);
});

for (const [label, block] of [["current", NEW_BLOCK], ["legacy", LEGACY_BLOCK]]) {
  test(`${label} block is removed from CLAUDE.md`, (t) => {
    const f = fixture(t);
    writeClaudeMd(f, `mine\n\n${block}\ntail\n`);
    const result = f.run();
    assert.equal(result.status, 0, result.stdout + result.stderr);
    // removeBlock drops the separator blank line when only one side of the block has one.
    assert.equal(fs.readFileSync(f.claudeMd, "utf8"), "mine\ntail\n");
    assert.equal(f.backups().filter((file) => path.basename(file).startsWith("CLAUDE.md.bak-")).length, 1);
    assert.ok(fs.existsSync(f.rulesFile));
  });
}

test("CLAUDE.md holding only the block stays as an empty file", (t) => {
  const f = fixture(t);
  writeClaudeMd(f, `${NEW_BLOCK}\n`);
  const result = f.run();
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), "");
});

test("malformed markers: rules file installed, CLAUDE.md untouched, non-zero exit", (t) => {
  const f = fixture(t);
  const malformed = "before\n<!-- BEGIN orchestration-kit:claude-md -->\nbody\n";
  writeClaudeMd(f, malformed);
  const result = f.run();
  assert.notEqual(result.status, 0, result.stdout + result.stderr);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), malformed);
  assert.ok(result.stderr.includes(f.claudeMd));
  assert.match(result.stderr, /unmatched-begin/);
  assert.match(result.stderr, /remove it by hand/);
  assert.ok(fs.existsSync(f.rulesFile));
  assert.ok(fs.existsSync(path.join(f.claude, "agents", "luna-worker.md")));
  // Uninstall still refuses before touching anything.
  const removed = f.run("--uninstall");
  assert.notEqual(removed.status, 0, removed.stdout + removed.stderr);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), malformed);
  assert.match(removed.stderr, /unmatched-begin/);
  assert.ok(fs.existsSync(f.rulesFile));
});

test("second install changes nothing", (t) => {
  const f = fixture(t);
  assert.equal(f.run().status, 0);
  const files = [f.rulesFile, f.settings];
  const before = files.map((file) => ({ content: fs.readFileSync(file, "utf8"), mtime: fs.statSync(file).mtimeMs }));
  const backupCount = f.backups().length;
  const result = f.run();
  assert.equal(result.status, 0, result.stdout + result.stderr);
  for (const [index, file] of files.entries()) {
    assert.equal(fs.readFileSync(file, "utf8"), before[index].content);
    assert.equal(fs.statSync(file).mtimeMs, before[index].mtime);
  }
  assert.equal(f.backups().length, backupCount);
});

for (const [label, corrupt] of [["hand-edited rules file is backed up", false], ["corrupt deployed.json counts as no record", true]]) {
  test(label, (t) => {
    const f = fixture(t);
    assert.equal(f.run().status, 0);
    fs.appendFileSync(f.rulesFile, "my local note\n");
    if (corrupt) fs.writeFileSync(f.deployed, "{");
    const result = f.run();
    assert.equal(result.status, 0, result.stdout + result.stderr);
    const kept = f.backups().filter((file) => file.includes(path.join("orchestration", "backups", "orchestration-kit.md.bak-")));
    assert.equal(kept.length, 1);
    assert.ok(fs.readFileSync(kept[0], "utf8").includes("my local note"));
    assert.equal(fs.readFileSync(f.rulesFile, "utf8").includes("my local note"), false);
    assert.equal(JSON.parse(fs.readFileSync(f.deployed, "utf8")).rules_file_sha256, sha256(f.rulesFile));
  });
}

test("rules path that is a directory stops the install before any change", (t) => {
  const f = fixture(t);
  const original = `mine\n\n${NEW_BLOCK}\n`;
  writeClaudeMd(f, original);
  fs.mkdirSync(f.rulesFile, { recursive: true });
  const result = f.run();
  assert.notEqual(result.status, 0, result.stdout + result.stderr);
  assert.ok(result.stderr.includes(f.rulesFile), result.stderr);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), original);
  assert.equal(fs.existsSync(path.join(f.claude, "orchestration", "scripts")), false);
});

test("--dry-run writes nothing", (t) => {
  const f = fixture(t);
  const original = `mine\n\n${NEW_BLOCK}\n`;
  writeClaudeMd(f, original);
  const result = f.run("--dry-run");
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(fs.existsSync(f.rulesFile), false);
  assert.equal(fs.readFileSync(f.claudeMd, "utf8"), original);
  assert.equal(f.backups().length, 0);
});

test("uninstall removes only the kit's rules file", (t) => {
  const f = fixture(t);
  assert.equal(f.run().status, 0);
  const mine = path.join(path.dirname(f.rulesFile), "mine.md");
  fs.writeFileSync(mine, "my own rule\n");
  const result = f.run("--uninstall");
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(fs.existsSync(f.rulesFile), false);
  assert.equal(fs.readFileSync(mine, "utf8"), "my own rule\n");
});

test("uninstall with no rules file succeeds", (t) => {
  const f = fixture(t);
  const result = f.run("--uninstall");
  assert.equal(result.status, 0, result.stdout + result.stderr);
});

test("AGENTS.md files untouched", (t) => {
  const f = fixture(t);
  const codexAgents = path.join(f.home, ".codex", "AGENTS.md");
  const project = path.join(f.dir, "proj");
  const projectAgents = path.join(project, "AGENTS.md");
  fs.mkdirSync(path.dirname(codexAgents), { recursive: true });
  fs.mkdirSync(project, { recursive: true });
  fs.writeFileSync(codexAgents, "codex user data\n");
  fs.writeFileSync(projectAgents, "project user data\n");
  const originals = [fs.readFileSync(codexAgents), fs.readFileSync(projectAgents)];
  const installed = f.run();
  assert.equal(installed.status, 0, installed.stdout + installed.stderr);
  assert.deepEqual(fs.readFileSync(codexAgents), originals[0]);
  assert.deepEqual(fs.readFileSync(projectAgents), originals[1]);
  const removed = f.run("--uninstall");
  assert.equal(removed.status, 0, removed.stdout + removed.stderr);
  assert.deepEqual(fs.readFileSync(codexAgents), originals[0]);
  assert.deepEqual(fs.readFileSync(projectAgents), originals[1]);
});

test("overrides survive reinstall and uninstall", (t) => {
  const f = fixture(t);
  assert.equal(f.run().status, 0);
  const override = path.join(f.claude, "orchestration", "overrides", "roles", "luna-test.md");
  fs.mkdirSync(path.dirname(override), { recursive: true });
  fs.writeFileSync(override, "user prompt\n");
  assert.equal(f.run().status, 0);
  assert.equal(fs.readFileSync(override, "utf8"), "user prompt\n");
  const removed = f.run("--uninstall");
  assert.equal(removed.status, 0, removed.stdout + removed.stderr);
  assert.equal(fs.readFileSync(override, "utf8"), "user prompt\n");
  const purged = f.run("--uninstall", "--purge");
  assert.equal(purged.status, 0, purged.stdout + purged.stderr);
  assert.equal(fs.existsSync(override), false);
});

