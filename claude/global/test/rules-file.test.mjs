// Tests for the generated rules file that carries the lead's global instructions.
//
//   node --test claude/global/test/rules-file.test.mjs

import test from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildRulesFile, RULES_FILE_NAME, RULES_SOURCES } from "../scripts/rules-file.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..", "..");
const GUARD = /\b(Opus|Fable|Sonnet|Haiku)\b/;

/** Build a throwaway kit root holding the three sources. Input: test context, optional per-file text. Output: root path. */
function tempKit(t, texts = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "rules-file-test-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  RULES_SOURCES.forEach((rel, index) => {
    const file = path.join(root, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    if (texts[rel] !== null) fs.writeFileSync(file, texts[rel] ?? `# Source ${index + 1}\n\nbody ${index + 1}\n`);
  });
  return root;
}

test("names and sources are fixed", () => {
  assert.equal(RULES_FILE_NAME, "orchestration-kit.md");
  assert.deepEqual(RULES_SOURCES, ["claude/global/CLAUDE.orchestration.md", "shared/ROUTING_POLICY.md", "claude/CLAUDE.md"]);
});

test("real kit: sources in order, no import lines", () => {
  const text = buildRulesFile({ kitRoot: REPO, commit: "abc1234" });
  assert.ok(text.startsWith("<!-- Generated by orchestration-kit install.mjs from kit commit abc1234. Do not edit: it is overwritten on every deploy.\n     Your own instructions belong in ~/.claude/CLAUDE.md or another file in this folder. -->\n\n"));
  const positions = RULES_SOURCES.map((rel) => {
    const heading = fs.readFileSync(path.join(REPO, rel), "utf8").split(/\r?\n/).find((line) => line.startsWith("# "));
    return text.indexOf(`\n${heading}\n`);
  });
  assert.ok(positions.every((p) => p > 0), JSON.stringify(positions));
  assert.deepEqual([...positions].sort((a, b) => a - b), positions);
  assert.equal(text.split("\n").find((line) => line.startsWith("@")), undefined);
});

test("real kit: no lead model name", () => {
  const lines = buildRulesFile({ kitRoot: REPO, commit: "abc1234" }).split("\n");
  const hit = lines.findIndex((line) => GUARD.test(line));
  assert.equal(hit, -1, lines[hit]);
});

test("deterministic and LF-only", (t) => {
  const root = tempKit(t, Object.fromEntries(RULES_SOURCES.map((rel, i) => [rel, `# S${i}\r\n\r\nbody\r\n\r\n\r\n`])));
  const first = buildRulesFile({ kitRoot: root, commit: "c1" });
  assert.equal(first, buildRulesFile({ kitRoot: root, commit: "c1" }));
  assert.equal(first.includes("\r"), false);
  assert.ok(first.endsWith("# S1\n\nbody\n\n# S2\n\nbody\n"), JSON.stringify(first.slice(-40)));
});

test("null commit is reported as unknown", (t) => {
  const text = buildRulesFile({ kitRoot: tempKit(t), commit: null });
  assert.ok(text.includes("from kit commit unknown."));
});

test("missing source throws with the file name", (t) => {
  const root = tempKit(t, { "shared/ROUTING_POLICY.md": null });
  assert.throws(() => buildRulesFile({ kitRoot: root, commit: "c1" }), /shared\/ROUTING_POLICY\.md/);
});

test("import line in a source throws with the file name", (t) => {
  const root = tempKit(t, { "claude/CLAUDE.md": "# Rules\n\n@~/somewhere/else.md\n" });
  assert.throws(() => buildRulesFile({ kitRoot: root, commit: "c1" }), /claude\/CLAUDE\.md/);
});

test("freeze manifest pins the generated rules file", () => {
  const manifest = JSON.parse(fs.readFileSync(path.join(HERE, "golden", "static-prompts.sha256.json"), "utf8"));
  const expected = crypto.createHash("sha256").update(buildRulesFile({ kitRoot: REPO, commit: "<commit>" })).digest("hex");
  assert.equal(manifest["generated/orchestration-kit.rules.md"], expected);
});

test("the manual command in GLOBAL_INSTALL.md writes a UTF-8 rules file", async (t) => {
  const { spawnSync } = await import("node:child_process");
  const doc = fs.readFileSync(path.join(REPO, "claude", "GLOBAL_INSTALL.md"), "utf8");
  const command = doc.match(/```bash\r?\n(node --input-type=module -e .*buildRulesFile.*)\r?\n```/)?.[1];
  assert.ok(command, "manual rules-file command not found in GLOBAL_INSTALL.md");
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "rules-manual-"));
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  // The documented command must write the file itself, so the shell's redirection encoding never matters.
  const script = command.match(/-e "(.*)"$/)[1];
  const r = spawnSync(process.execPath, ["--input-type=module", "-e", script], { cwd: REPO, encoding: "utf8", env: { ...process.env, HOME: home, USERPROFILE: home } });
  assert.equal(r.status, 0, r.stderr);
  const written = fs.readFileSync(path.join(home, ".claude", "rules", RULES_FILE_NAME));
  assert.equal(written.subarray(0, 4).toString("utf8"), "<!--");
  assert.equal(written.toString("utf8"), buildRulesFile({ kitRoot: REPO, commit: null }));
});
