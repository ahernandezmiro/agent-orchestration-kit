// Builds the rules file that carries the lead's global instructions into Claude Code.
// Author: maintained with Claude Code for the frontier-model orchestration setup.
//
// Claude Code loads every Markdown file in ~/.claude/rules/ in every project, so the kit owns one
// file there and never edits the user's CLAUDE.md. The file is flat (no @ imports): the sources
// are concatenated at install time. Pure function; the installer does the file I/O.
// See docs/superpowers/specs/2026-11-17-lead-neutral-global-instructions-design.md §2.

import fs from "node:fs";
import path from "node:path";

/** File name of the kit's rules file inside ~/.claude/rules/. */
export const RULES_FILE_NAME = "orchestration-kit.md";

/** Kit-relative source files, in the order they appear in the rules file. */
export const RULES_SOURCES = ["claude/global/CLAUDE.orchestration.md", "shared/ROUTING_POLICY.md", "claude/CLAUDE.md"];

/**
 * Build the text of the rules file.
 * Input: { kitRoot: kit checkout (absolute path), commit: short commit id or null }.
 * Output: the file text, LF line endings, ending with one newline.
 * Throws when a source is missing or contains an @ import line.
 */
export function buildRulesFile({ kitRoot, commit }) {
  const header = [
    `<!-- Generated by orchestration-kit install.mjs from kit commit ${commit || "unknown"}. Do not edit: it is overwritten on every deploy.`,
    "     Your own instructions belong in ~/.claude/CLAUDE.md or another file in this folder. -->"
  ].join("\n");
  const sections = RULES_SOURCES.map((rel) => {
    const file = path.join(kitRoot, rel);
    if (!fs.existsSync(file)) throw new Error(`rules file source missing: ${rel}`);
    const text = fs.readFileSync(file, "utf8").replace(/^﻿/, "").replace(/\r\n|\r/g, "\n").trimEnd();
    const importLine = text.split("\n").findIndex((line) => line.startsWith("@"));
    if (importLine >= 0) throw new Error(`rules file source ${rel} has an @ import at line ${importLine + 1}; the rules file must be flat`);
    return text;
  });
  return `${[header, ...sections].join("\n\n")}\n`;
}
